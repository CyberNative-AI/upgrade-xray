// Yarn (1 and 2+) and bun lockfiles: which names may leave the run, and what is refused. Every
// lookup test runs the real lockfile → analysis path and records every outbound request.
import test from 'node:test';
import assert from 'node:assert/strict';
import { runInput } from '../src/main.js';
import { parseLockfile, detectType, parseYarnV1 } from '../src/lockfile.js';
import { stubFetch, lookedUpNames, memoryIo } from './helpers.js';

async function outbound(before, after, extra = {}) {
    const f = stubFetch();
    try {
        const io = memoryIo();
        await runInput({ lockfileBefore: before, lockfileAfter: after, concurrency: 1, ...extra }, io);
        return { names: lookedUpNames(f.calls), io };
    } finally { f.restore(); }
}

const HEADER = '# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.\n# yarn lockfile v1\n\n';
const yarn1 = (entries) => HEADER + entries.map((e) => `\n${e}\n`).join('');
const y1 = (keys, version, resolved) => `${keys}:\n  version "${version}"\n${resolved ? `  resolved "${resolved}"\n` : ''}  integrity sha512-abc==`;

test('Yarn 1: public "resolved" is looked up by default; private, git and local entries never are', async () => {
    const lock = (v) => yarn1([
        y1('left-pad@^1.0.0', v, `https://registry.yarnpkg.com/left-pad/-/left-pad-${v}.tgz#abc`),
        y1('"@scope/pub@^1.0.0"', v, `https://registry.npmjs.org/@scope/pub/-/pub-${v}.tgz`),
        y1('corp-secret@^1.0.0', v, `https://npm.corp.example/corp-secret/-/corp-secret-${v}.tgz`),
        y1('"gitdep@github:o/gitdep"', v, `git+https://github.com/o/gitdep.git#abc${v}`),
        y1('"localdep@file:../localdep"', v),
    ]);
    const { names, io } = await outbound(lock('1.0.0'), lock('1.1.0'), { lockfileName: 'yarn.lock' });
    assert.deepEqual(names.sort(), ['@scope/pub', 'left-pad']);
    assert.deepEqual(io.kv.OUTPUT.nonRegistry.map((n) => [n.name, n.origin]).sort(), [['corp-secret', 'private'], ['gitdep', 'git'], ['localdep', 'local']]);
    assert.equal(io.kv.OUTPUT.lockfileType, 'yarn');
    assert.match(io.kv.REPORT, /^Yarn 1 lockfile: \*\*2 updated/m);
    // A local or git range without "resolved" is never sent, even when the user confirms the public registry.
    const opt = await outbound(lock('1.0.0'), lock('1.1.0'), { lockfileName: 'yarn.lock', assumePublicRegistry: true });
    assert.deepEqual(opt.names.sort(), ['@scope/pub', 'left-pad']);
});

test('Yarn 1: no "resolved" and a plain range is unknown and needs confirmation', async () => {
    const lock = (v) => yarn1([y1('quiet@^1.0.0', v)]);
    assert.deepEqual((await outbound(lock('1.0.0'), lock('1.0.1'), { lockfileName: 'yarn.lock' })).names, []);
    assert.deepEqual((await outbound(lock('1.0.0'), lock('1.0.1'), { lockfileName: 'yarn.lock', assumePublicRegistry: true })).names, ['quiet']);
});

test('Yarn 1: an alias installs the real package, which is the name looked up', () => {
    const p = parseLockfile(yarn1([y1('"string-width-cjs@npm:string-width@^4.2.0", string-width@^4.1.0', '4.2.3', 'https://registry.yarnpkg.com/string-width/-/string-width-4.2.3.tgz')]), 'yarn.lock');
    assert.deepEqual([...p.packages.keys()], ['string-width']);
    assert.equal(p.packages.get('string-width').get('4.2.3').origin, 'public');
    assert.throws(() => parseLockfile(yarn1([y1('a@^1, b@^1', '1.0.0')]), 'yarn.lock'), /one entry names different packages/);
});

test('Yarn 1: syntax outside what Yarn writes is refused, not read differently', () => {
    const ok = yarn1([y1('a@^1', '1.0.0'), 'b@^1:\n  version "1.0.0"\n  dependencies:\n    a "^1"\n    "@s/c" "*"']);
    assert.deepEqual(parseYarnV1(ok).map((e) => e.keys), [['a@^1'], ['b@^1']]);
    assert.deepEqual(parseYarnV1(ok)[1].fields.dependencies, { a: '^1', '@s/c': '*' });
    const refused = {
        'duplicate key': yarn1([y1('a@^1', '1.0.0'), y1('a@^1', '2.0.0')]),
        'duplicate field': 'a@^1:\n  version "1.0.0"\n  version "2.0.0"\n',
        'backslash in a string': 'a@^1:\n  version "1.0.0"\n  resolved "https://registry.npmjs.org/a\\"/-/a.tgz"\n',
        'tab indentation': 'a@^1:\n\tversion "1.0.0"\n',
        'odd indentation': 'a@^1:\n   version "1.0.0"\n',
        'skipped level': 'a@^1:\n    version "1.0.0"\n',
        'value with a colon': 'a@^1:\n  version 1:0\n',
        'field at top level': 'version "1.0.0"\n',
        'lone carriage return': 'a@^1:\r  version "1.0.0"\n',
        'number value': 'a@^1:\n  version 1\n',
    };
    for (const [why, text] of Object.entries(refused)) assert.throws(() => parseLockfile(text, 'yarn.lock'), /yarn\.lock/, why);
});

const berry = (entries) => `# This file is generated by running "yarn install" inside your project.\n# Manual changes might be lost - proceed with caution!\n\n__metadata:\n  version: 8\n  cacheKey: 10c0\n${entries.map((e) => `\n${e}\n`).join('')}`;
const b2 = (key, resolution, version) => `"${key}":\n  version: ${version}\n  resolution: "${resolution}"\n  checksum: 10c0/abc\n  languageName: node\n  linkType: hard`;

test('Yarn 2+: registry packages have no recorded registry and need confirmation; patches, git and workspaces never leave', async () => {
    const lock = (v) => berry([
        b2('quiet@npm:^1.0.0', `quiet@npm:${v}`, v),
        b2('typescript@patch:typescript@npm%3A^5#optional!builtin<compat/typescript>', `typescript@patch:typescript@npm%3A${v}#optional!builtin<compat/typescript>::version=${v}&hash=5786d5`, v),
        b2('gitdep@https://github.com/o/gitdep.git', `gitdep@https://github.com/o/gitdep.git#commit=abc${v}`, v),
        b2('app@workspace:.', 'app@workspace:.', '0.0.0-use.local'),
    ]);
    const def = await outbound(lock('1.0.0'), lock('1.0.1'), { lockfileName: 'yarn.lock' });
    assert.deepEqual(def.names, []);
    assert.equal(def.io.kv.OUTPUT.lockfileType, 'yarn-berry');
    assert.match(def.io.kv.REPORT, /^Yarn 2\+ lockfile: \*\*0 updated/m);
    assert.match(def.io.kv.REPORT, /no recorded origin: Yarn 2 and later do not record the registry/);
    const opt = await outbound(lock('1.0.0'), lock('1.0.1'), { lockfileName: 'yarn.lock', assumePublicRegistry: true });
    assert.deepEqual(opt.names, ['quiet']);
    assert.deepEqual(opt.io.kv.OUTPUT.nonRegistry.map((n) => [n.name, n.origin]).sort(), [['gitdep', 'git'], ['typescript', 'local']]);
    // The version comes from the resolution, not from YAML's reading of "version: 1.10" as a number.
    assert.deepEqual([...parseLockfile(berry([b2('n@npm:^1', 'n@npm:1.10', '1.10')]), 'yarn.lock').packages.get('n').keys()], ['1.10']);
    assert.throws(() => parseLockfile(berry(['"a@npm:^1":\n  version: 1.0.0']), 'yarn.lock'), /no resolution/);
});

const bun = (pkgs, ws = '{ "": { "name": "app" }, }') => `{\n  "lockfileVersion": 1,\n  "workspaces": ${ws},\n  "packages": {\n${pkgs.map((p) => `    ${p},\n`).join('')}  }\n}\n`;

test('bun.lock: the default registry is unknown; a named public registry is looked up; private and git never are', async () => {
    const lock = (v) => bun([
        `"quiet": ["quiet@${v}", "", {}, "sha512-x"]`,
        `"named-pub": ["named-pub@${v}", "https://registry.npmjs.org/", {}, "sha512-x"]`,
        `"@corp/secret": ["@corp/secret@${v}", "https://npm.pkg.github.com/", {}, "sha512-x"]`,
        `"gitdep": ["gitdep@github:o/gitdep#abc${v}", {}, "o-gitdep-abc"]`,
        `"alias": ["real-pkg@${v}", "", {}, "sha512-x"]`,
        `"ws-lib": ["ws-lib@workspace:packages/ws-lib"]`,
    ]);
    const def = await outbound(lock('1.0.0'), lock('1.0.1'), { lockfileName: 'bun.lock' });
    assert.deepEqual(def.names, ['named-pub']);
    assert.equal(def.io.kv.OUTPUT.lockfileType, 'bun');
    const opt = await outbound(lock('1.0.0'), lock('1.0.1'), { lockfileName: 'bun.lock', assumePublicRegistry: true });
    assert.deepEqual(opt.names.sort(), ['named-pub', 'quiet', 'real-pkg']);
    assert.deepEqual(opt.io.kv.OUTPUT.nonRegistry.map((n) => [n.name, n.origin]).sort(), [['@corp/secret', 'private'], ['gitdep', 'git']]);
});

test('bun.lock: trailing commas are read; comments, bad entries and the binary format are refused', () => {
    assert.deepEqual([...parseLockfile(bun(['"a": ["a@1.0.0", "", {}, "sha512-x",]']), 'bun.lock').packages.keys()], ['a']);
    assert.deepEqual([...parseLockfile(bun(['"a": ["a@1.0.0", "", { "x": "has, ] inside" }, "s"]']), 'bun.lock').packages.keys()], ['a']);
    assert.throws(() => parseLockfile(bun(['// note\n    "a": ["a@1.0.0", "", {}, "s"]']), 'bun.lock'), /comment/);
    assert.throws(() => parseLockfile(bun(['"a": { "version": "1.0.0" }']), 'bun.lock'), /not a list/);
    assert.throws(() => parseLockfile('{"lockfileVersion": 1, "workspaces": {}}', 'bun.lock'), /no "packages"/);
    assert.throws(() => parseLockfile('\x00\x01binary', 'bun.lockb'), /binary lockfile/);
});

test('format detection without a file name, and npm lockfiles stay npm', () => {
    assert.equal(detectType(yarn1([y1('a@^1', '1.0.0')])), 'yarn');
    assert.equal(detectType(berry([b2('a@npm:^1', 'a@npm:1.0.0', '1.0.0')])), 'yarn-berry');
    assert.equal(detectType(bun(['"a": ["a@1.0.0", "", {}, "s"]'])), 'bun');
    assert.equal(detectType(bun([])), 'bun');
    assert.equal(detectType(JSON.stringify({ lockfileVersion: 3, packages: { '': { name: 'app', workspaces: ['x'] }, 'node_modules/a': { version: '1.0.0' } } })), 'npm');
    assert.equal(detectType(JSON.stringify({ lockfileVersion: 3, workspaces: { a: 1 }, packages: { 'node_modules/a': { version: '1.0.0' } } })), 'npm');
    assert.throws(() => detectType('<html>not a lockfile</html>'), /yarn\.lock, bun\.lock/);
});

test('Yarn 1: long space runs and long comments are read in linear time; a line over 16 KiB is refused', () => {
    const run = ' '.repeat(16000);
    const entry = y1('left-pad@^1.0.0', '1.1.0', 'https://registry.yarnpkg.com/left-pad/-/left-pad-1.1.0.tgz');
    const start = process.hrtime.bigint();
    // 64 comment lines just under the cap, each a space run, then a real entry.
    const comments = Array.from({ length: 64 }, () => `#${run}x`).join('\n');
    assert.deepEqual(parseYarnV1(`${HEADER}${comments}\n\n${entry}\n`).map((e) => e.keys), [['left-pad@^1.0.0']]);
    // 64 key lines with a space run inside, each refused on its own.
    for (let i = 0; i < 64; i++) assert.throws(() => parseYarnV1(`${HEADER}a${run}b:\n`), /not a key|not a field/);
    const ms = Number(process.hrtime.bigint() - start) / 1e6;
    assert.ok(ms < 2000, `took ${ms} ms`);
    for (const line of [`#${' '.repeat(65536)}x`, `a${' '.repeat(65536)}b:`]) {
        assert.throws(() => parseYarnV1(`${HEADER}${line}\n`), /line 4: it is longer than 16384 characters/);
    }
});
